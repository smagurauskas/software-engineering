"""Measures the examples of the software construction lecture with real tools and
writes the results to reports/, which the lecture includes.

    python measure.py          # re-measure and write reports/
    python measure.py --check  # re-measure and fail if reports/ is out of date (CI)

Tools used:
- .NET code metrics rules CA1502 (cyclomatic complexity), CA1505 (maintainability index)
  and CA1506 (class coupling), built with zero thresholds so every member is reported
- Stryker.NET (mutation testing), once with the weak tests and once with the strong ones
- `dotnet list package` (direct and transitive dependencies)
"""

import argparse
import difflib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPORTS = ROOT / "reports"
PROJECT = ROOT / "WordGame.Construction"
HEADER = "# Generated by measure.py - do not edit, re-run `python measure.py` instead.\n"

DIAGNOSTIC = re.compile(
    r"(?P<file>[\w.]+\.cs)\((?P<line>\d+),(?P<col>\d+)\): warning (?P<rule>CA150[256]): (?P<message>.*?) \["
)


def run(*args, cwd=ROOT):
    result = subprocess.run(args, cwd=cwd, capture_output=True, text=True, encoding="utf-8")
    if result.returncode != 0:
        sys.exit(f"`{' '.join(args)}` failed:\n{result.stdout}\n{result.stderr}")
    return result.stdout


def diagnostics(*build_args):
    output = run("dotnet", "build", str(PROJECT), "--no-incremental", *build_args)
    # MSBuild prints every warning twice: when it happens and in the summary
    return sorted({tuple(m.groupdict().values()) for m in DIAGNOSTIC.finditer(output)})


def number(pattern, message):
    return int(re.search(pattern, message).group(1))


def code_metrics():
    """Metrics of every type and member, keyed by (file, member)."""
    by_position = defaultdict(dict)
    for file, line, col, rule, message in diagnostics("-p:MeasureAll=true"):
        entry = by_position[(file, int(line), int(col))]
        if rule == "CA1502":
            entry["cyclomatic"] = number(r"complexity of '(\d+)'", message)
        elif rule == "CA1505":
            entry["name"] = re.match(r"'([^']+)'", message).group(1)
            entry["maintainability"] = number(r"index of '(\d+)'", message)
        elif rule == "CA1506":
            entry["coupling"] = number(r"coupled with '(\d+)'", message)

    metrics = {}
    for (file, line, _), entry in by_position.items():
        if "name" in entry:
            # Values at the lowest possible level are not reported: cyclomatic complexity 1
            # and coupling to at most one type
            metrics[(file, entry["name"])] = {"cyclomatic": 1, "coupling": "≤1", **entry, "line": line}
    return metrics


def table(rows, columns):
    widths = [max(len(str(r[i])) for r in [columns, *rows]) for i in range(len(columns))]
    # Numbers are right-aligned, text left-aligned
    numeric = [all(isinstance(r[i], int) or str(r[i]).rstrip("%").lstrip("≤").isdigit() for r in rows) for i in range(len(columns))]
    line = lambda r: " | ".join(str(v).rjust(w) if numeric[i] else str(v).ljust(w) for i, (v, w) in enumerate(zip(r, widths))).rstrip()
    return "\n".join([line(columns), "-|-".join("-" * w for w in widths), *map(line, rows)])


def members(metrics, file):
    """Methods of a file (not the type itself, constructors or fields), in source order."""
    type_name = file.removesuffix(".cs")
    return sorted(
        ((name, m) for (f, name), m in metrics.items() if f == file and name != type_name and name[0].isupper()),
        key=lambda item: item[1]["line"],
    )


def complexity_report(metrics):
    columns = ("Method", "Cyclomatic", "Maintainability", "Coupling")
    row = lambda name, m: (name, m["cyclomatic"], m["maintainability"], m["coupling"])

    def methods(file):
        return [(name, m) for name, m in members(metrics, file) if name not in ("MaxExperience", "FastGame")]

    def summary(label, file):
        ms = methods(file)
        type_metrics = metrics[(file, file.removesuffix(".cs"))]
        return (
            label,
            len(ms),
            sum(m["cyclomatic"] for _, m in ms),
            max(m["cyclomatic"] for _, m in ms),
            type_metrics["maintainability"],
        )

    calculators = [
        ("Before", "ExperienceCalculatorBefore.cs"),
        ("After", "ExperienceCalculator.cs"),
        ("Over-split", "ExperienceCalculatorOverSplit.cs"),
    ]

    sections = {
        "before": table([row(f"ExperienceCalculatorBefore.{n}", m) for n, m in methods("ExperienceCalculatorBefore.cs")], columns),
        "after": table([row(n, m) for n, m in methods("ExperienceCalculator.cs")], columns),
        "summary": table(
            [summary(label, file) for label, file in calculators],
            ("Version", "Methods", "Cyclomatic, all methods", "Cyclomatic, most complex method", "Maintainability"),
        ),
        "readability": table([row(n, m) for n, m in methods("Readability.cs")], columns),
    }
    return sections


def build_report():
    # The normal build, with the thresholds a team would use
    lines = [f"{file}({line},{col}): warning {rule}: {message}" for file, line, col, rule, message in diagnostics()]
    return {"build": "\n".join(lines)}


def mutation_report():
    sections = {}
    rows = []
    for label, tests in (("Weak tests", "WordGame.Construction.WeakTests"), ("Characterization tests", "WordGame.Construction.Tests")):
        output = Path(tempfile.mkdtemp())
        try:
            run(
                "dotnet", "stryker",
                "--test-runner", "mtp",
                "--project", "WordGame.Construction.csproj",
                "--mutate", "**/Complexity/ExperienceCalculator.cs",
                "--reporter", "json",
                "--output", str(output),
                cwd=ROOT / tests,
            )
            report = json.loads(next(output.rglob("mutation-report.json")).read_text(encoding="utf-8"))
        finally:
            shutil.rmtree(output, ignore_errors=True)

        mutants = [m for f in report["files"].values() for m in f["mutants"] if m["status"] in ("Killed", "Survived", "NoCoverage", "Timeout")]
        killed = sum(m["status"] in ("Killed", "Timeout") for m in mutants)
        rows.append((label, len(mutants), killed, len(mutants) - killed, f"{killed / len(mutants):.0%}"))

        survivors = sorted((m for m in mutants if m["status"] not in ("Killed", "Timeout")), key=lambda m: m["location"]["start"]["line"])
        if label == "Characterization tests":
            sections["survivors"] = table(
                [(m["location"]["start"]["line"], m["mutatorName"], m.get("replacement") or "") for m in survivors],
                ("Line", "Mutation", "Replaced with"),
            )

    sections["score"] = table(rows, ("Tests", "Mutants", "Killed", "Survived", "Score"))
    return sections


def dependency_report():
    output = run("dotnet", "list", str(ROOT.parent / "07-testing" / "WordGame.slnx"), "package", "--include-transitive", "--format", "json")
    rows = []
    for project in json.loads(output)["projects"]:
        for framework in project.get("frameworks", []):
            direct = framework.get("topLevelPackages", [])
            rows.append((
                os.path.basename(project["path"]).removesuffix(".csproj"),
                len(direct),
                len(framework.get("transitivePackages", [])),
                ", ".join(p["id"] for p in direct),
            ))
    return {"dependencies": table(rows, ("Project", "Direct", "Transitive", "Direct packages"))}


def render(sections):
    parts = [HEADER]
    for name, text in sections.items():
        parts.append(f"\n# #region {name}\n{text}\n# #endregion {name}\n")
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if reports/ differs from the measurements")
    args = parser.parse_args()

    reports = {
        "complexity.txt": complexity_report(code_metrics()),
        "build.txt": build_report(),
        "mutation.txt": mutation_report(),
        "dependencies.txt": dependency_report(),
    }

    REPORTS.mkdir(exist_ok=True)
    outdated = []
    for name, sections in reports.items():
        path = REPORTS / name
        text = render(sections)
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != text:
                outdated.append(name)
                sys.stdout.writelines(difflib.unified_diff(current.splitlines(True), text.splitlines(True), f"committed/{name}", f"measured/{name}"))
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote reports/{name}")

    if outdated:
        sys.exit(f"\nOut of date: {', '.join(outdated)}. Run `python measure.py` and commit reports/.")


if __name__ == "__main__":
    main()
